"""``sandbox tools --world <name>``: a world's tool reference, from the schemas its agent sees.

The tools are read from an episode's tool router, the same list the MCP bridge serves
(:class:`kit.mcp_bridge.McpBridge`), so the reference cannot drift from what the agent is
offered. The docs site's ``tools/<world>.md`` pages are this output, kept current by a test.
"""

from __future__ import annotations

import json
from typing import Any

from kit.clock import SimClock
from kit.rng import SeededRNG
from kit.world import WorldSpec


def tool_list(spec: WorldSpec) -> list[dict[str, Any]]:
    """Every tool of a world, in its router's order: name, description and input schema."""
    tasks = spec.task_source().tasks
    if not tasks:
        msg = f"world {spec.name!r} has no tasks to build an episode from"
        raise ValueError(msg)
    episode = spec.make_episode(tasks[0], SimClock(), SeededRNG(0))
    try:
        router = getattr(episode, "router", None)
        if router is None:
            msg = f"world {spec.name!r} has no tool router to read its tools from"
            raise ValueError(msg)
        tools = [router.get(name) for name in router.names]
    finally:
        episode.close()
    return [
        {"name": tool.name, "description": tool.description, "input_schema": tool.input_schema}
        for tool in tools
    ]


def _type(schema: dict[str, Any], defs: dict[str, Any]) -> str:
    """A short type for a table cell: ``string``, ``integer or null``, an enum, ``array of x``."""
    if "$ref" in schema:
        return _type(defs.get(str(schema["$ref"]).rsplit("/", 1)[-1], {}), defs)
    if "anyOf" in schema:
        return " or ".join(_type(option, defs) for option in schema["anyOf"])
    if "enum" in schema:
        return " \\| ".join(f"`{json.dumps(value)}`" for value in schema["enum"])
    kind = schema.get("type", "any")
    if isinstance(kind, list):
        kind = " or ".join(kind)
    if kind == "array" and isinstance(schema.get("items"), dict):
        return f"array of {_type(schema['items'], defs)}"
    return str(kind)


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def markdown(spec: WorldSpec) -> str:
    """The reference page for one world."""
    tools = tool_list(spec)
    lines = [
        f"# Tool reference: {spec.name}",
        "",
        f"Generated by `sandbox tools --world {spec.name}` from the schemas the agent is given "
        f"({len(tools)} tools, task set `{spec.name}-{spec.version}`). A task may allow only "
        "some of them (`allowed_tools`).",
        "",
    ]
    for tool in tools:
        schema = tool["input_schema"]
        properties: dict[str, Any] = schema.get("properties", {})
        required = set(schema.get("required", []))
        defs: dict[str, Any] = schema.get("$defs", {})
        lines += [f"## `{tool['name']}`", "", tool["description"].strip(), ""]
        if properties:
            lines += ["| argument | type | required | description |", "| --- | --- | --- | --- |"]
            for arg, prop in properties.items():
                lines.append(
                    f"| `{arg}` | {_type(prop, defs)} | {'yes' if arg in required else 'no'} | "
                    f"{_cell(str(prop.get('description', '')))} |"
                )
        else:
            lines.append("No arguments.")
        lines += [
            "",
            "```json",
            json.dumps(schema, indent=2, sort_keys=True),
            "```",
            "",
        ]
    return "\n".join(lines)


__all__ = ["markdown", "tool_list"]
